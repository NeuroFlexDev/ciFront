import DOMPurify from "dompurify";
import { plantUmlToMermaid } from "./plantUml";

export const DIAGRAM_LANGUAGES = new Set([
  "mermaid",
  "uml",
  "plantuml",
  "diagram",
]);
export const DIAGRAM_LIMITS = { characters: 12000, lines: 160, edges: 120 };
export type DiagramResult = { svg: string; width: number; height: number };

/** The UML fences accept Mermaid's UML class/state/sequence syntax, never a server URL. */
export function diagramSource(source: string, kind = "mermaid"): string {
  if (!DIAGRAM_LANGUAGES.has(kind.toLowerCase()))
    throw new Error("Неизвестный формат схемы.");
  let text = source.trim();
  if (
    !text ||
    text.length > DIAGRAM_LIMITS.characters ||
    text.split("\n").length > DIAGRAM_LIMITS.lines
  )
    throw new Error(
      "Схема слишком большая. Разделите её на несколько схем (до 12 000 символов и 160 строк).",
    );
  if (/^@startuml/i.test(text)) text = plantUmlToMermaid(text);
  if (
    /%%\s*\{|^\s*---|<\/?[a-z!]|\b(?:https?|javascript|data|file|ftp):|@|\\|url\s*\(|(?:^|[;\n])\s*(?:click|link|links|callback|style|classDef|linkStyle|cssClass|icon|image|!include)\b/im.test(
      text,
    )
  )
    throw new Error(
      "Схема содержит недопустимые ссылки, HTML, стили или директивы. Используйте обычные подписи и связи.",
    );
  const first =
    text
      .split("\n")
      .find((line) => line.trim() && !line.trim().startsWith("%%"))
      ?.trim() ?? "";
  if (
    !/^(?:flowchart\s+(?:TB|TD|BT|LR|RL)|graph\s+(?:TB|TD|BT|LR|RL)|sequenceDiagram|classDiagram|stateDiagram(?:-v2)?|erDiagram|gantt|pie(?:\s+showData)?|journey|timeline|mindmap|quadrantChart|xychart(?:-beta)?)\b/.test(
      first,
    )
  )
    throw new Error(
      "Начните схему с flowchart, sequenceDiagram, classDiagram, stateDiagram-v2, erDiagram, gantt, pie, journey, timeline, mindmap, quadrantChart или xychart.",
    );
  if (
    (text.match(/(?:--|==|\.\.|->|<-)/g) ?? []).length > DIAGRAM_LIMITS.edges ||
    text.split(/[\s;]+/).length > 2000
  )
    throw new Error(
      "В схеме слишком много связей. Разделите её на несколько небольших схем.",
    );
  return text;
}

const presentation = [
  "fill",
  "fill-opacity",
  "stroke",
  "stroke-width",
  "stroke-opacity",
  "stroke-dasharray",
  "stroke-dashoffset",
  "stroke-linecap",
  "stroke-linejoin",
  "font-family",
  "font-size",
  "font-weight",
  "font-style",
  "text-anchor",
  "dominant-baseline",
  "opacity",
  "color",
];
const svgTags = new Set([
  "svg",
  "g",
  "defs",
  "marker",
  "path",
  "rect",
  "circle",
  "ellipse",
  "line",
  "polyline",
  "polygon",
  "text",
  "tspan",
  "title",
  "desc",
  "clipPath",
  "linearGradient",
  "radialGradient",
  "stop",
]);

/** Flatten only computed presentation properties, then strip everything executable or external. */
export function sanitizeDiagram(
  svg: string,
  host?: HTMLElement,
): DiagramResult {
  if (svg.length > 2_000_000)
    throw new Error("Полученная схема превышает допустимый размер.");
  const parsed = new DOMParser().parseFromString(svg, "image/svg+xml");
  if (
    parsed.querySelector("parsererror") ||
    parsed.documentElement.localName !== "svg"
  )
    throw new Error("Не удалось прочитать SVG схемы.");
  const root = parsed.documentElement;
  const live = host?.querySelector("svg");
  // Mermaid CSS is generated by the bundled library; no user CSS is accepted.
  const sourceElements = live
    ? [live, ...Array.from(live.querySelectorAll("*"))]
    : [];
  const elements = [root, ...Array.from(root.querySelectorAll("*"))];
  for (let index = 0; index < elements.length; index++) {
    const element = elements[index];
    if (!svgTags.has(element.localName)) {
      element.remove();
      continue;
    }
    const original = sourceElements[index];
    if (original && original.localName === element.localName) {
      const computed = getComputedStyle(original);
      for (const property of presentation) {
        const value = computed.getPropertyValue(property);
        if (value && !/url\s*\(|[<>\\]|@/i.test(value))
          element.setAttribute(property, value);
      }
    }
    for (const attr of Array.from(element.attributes)) {
      const value = attr.value;
      if (
        /^on/i.test(attr.name) ||
        ["style", "class", "href", "xlink:href", "src"].includes(attr.name) ||
        (/(?:https?|data|javascript|file):|@|\\/i.test(value) &&
          !attr.name.startsWith("xmlns")) ||
        (/url\s*\(/i.test(value) && !/^url\(#[\w:.-]+\)$/.test(value))
      )
        element.removeAttribute(attr.name);
    }
  }
  const box = root
    .getAttribute("viewBox")
    ?.split(/[\s,]+/)
    .map(Number);
  if (
    !box ||
    box.length !== 4 ||
    !box.every(Number.isFinite) ||
    box[2] <= 0 ||
    box[3] <= 0 ||
    box[2] > 30000 ||
    box[3] > 30000
  )
    throw new Error("Схема не имеет допустимых размеров.");
  root.setAttribute("width", String(box[2]));
  root.setAttribute("height", String(box[3]));
  root.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  const clean = DOMPurify.sanitize(
    new XMLSerializer().serializeToString(root),
    {
      USE_PROFILES: { svg: true },
      FORBID_TAGS: [
        "foreignObject",
        "style",
        "a",
        "image",
        "use",
        "animate",
        "set",
        "script",
      ],
      FORBID_ATTR: ["style", "href", "xlink:href"],
      RETURN_TRUSTED_TYPE: false,
    },
  );
  return { svg: clean, width: box[2], height: box[3] };
}

let queue: Promise<unknown> = Promise.resolve();
let serial = 0;

/** Shared by reader, editor and PDF export. No network, callbacks or external renderer. */
export async function renderDiagram(
  source: string,
  kind = "mermaid",
  options: { theme?: "dark" | "print" } = {},
): Promise<DiagramResult> {
  const text = diagramSource(source, kind);
  const task = async () => {
    const { default: mermaid } = await import("mermaid");
    const host = document.createElement("div");
    host.setAttribute("aria-hidden", "true");
    host.style.cssText =
      "position:fixed;left:-40000px;top:0;width:1600px;visibility:hidden;pointer-events:none";
    document.body.append(host);
    try {
      mermaid.initialize({
        startOnLoad: false,
        securityLevel: "strict",
        suppressErrorRendering: true,
        theme: options.theme === "print" ? "neutral" : "dark",
        look: "classic",
        layout: "dagre",
        htmlLabels: false,
        maxTextSize: DIAGRAM_LIMITS.characters,
        maxEdges: DIAGRAM_LIMITS.edges,
        deterministicIds: true,
        fontFamily: "Arial, sans-serif",
        flowchart: { htmlLabels: false, useMaxWidth: false },
        journey: { textPlacement: "tspan" },
        secure: [
          "securityLevel",
          "htmlLabels",
          "maxTextSize",
          "maxEdges",
          "theme",
          "themeCSS",
          "fontFamily",
          "layout",
          "look",
        ],
      });
      const { svg } = await mermaid.render(
        `lernium-diagram-${++serial}`,
        text,
        host,
      );
      // Mermaid removes its temporary render tree before resolving. Reattach
      // its strict/sanitized SVG so computed library CSS can be flattened for PDF.
      const prepared = DOMPurify.sanitize(svg, {
        USE_PROFILES: { svg: true },
        FORBID_TAGS: [
          "foreignObject",
          "a",
          "image",
          "use",
          "animate",
          "set",
          "script",
        ],
        FORBID_ATTR: ["href", "xlink:href"],
        RETURN_TRUSTED_TYPE: false,
      });
      host.innerHTML = prepared;
      return sanitizeDiagram(prepared, host);
    } catch (reason) {
      if (reason instanceof Error && reason.message.startsWith("Схема"))
        throw reason;
      throw new Error(
        "Не удалось построить схему. Проверьте её синтаксис; исходный текст сохранён.",
      );
    } finally {
      host.remove();
    }
  };
  const next = queue.then(task, task);
  queue = next.catch(() => undefined);
  return next;
}
